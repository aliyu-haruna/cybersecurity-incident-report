// Shared notification panel used by the Reporter, Investigator and
// Administrator dashboards.
//
// Prototype scope: notifications are records written to localStorage by the
// workflow itself (submission, review, assignment, investigation completion,
// resolution and closure). Nothing is emailed or pushed. Marking a
// notification as read only sets the isRead flag in the stored record.
function notificationPanelHtml(user, options) {
  const opts = options || {};
  const limit = opts.limit || 5;
  const all = getNotificationsFor(user.id);
  const unread = all.filter((n) => n.isRead !== true).length;
  const rows = all.slice(0, limit);
  const more = all.length - rows.length;

  const toolbar =
    '<div class="notif-toolbar">' +
    '<p class="readonly-note" style="margin:0">Prototype notifications generated by workflow events. ' +
    (!all.length
      ? 'No notifications yet.'
      : all.length +
        ' total &middot; ' +
        (unread ? unread + ' unread' : 'all read')) +
    '</p>' +
    (unread
      ? '<button class="btn btn-secondary" type="button" data-mark-read>Mark all as read</button>'
      : '<span class="tag">All caught up</span>') +
    '</div>';

  if (!rows.length) {
    return toolbar + '<p class="empty-state">You have no notifications.</p>';
  }

  const items = rows
    .map((n) => {
      const isRead = n.isRead === true;
      const link = n.incidentId
        ? '<a href="incident-details.html?id=' + encodeURIComponent(n.incidentId) + '">View incident ' + escapeHtml(n.incidentId) + '</a>'
        : '';
      return (
        '<div class="notif' + (isRead ? '' : ' unread') + '">' +
        '<div class="notif-body">' +
        '<p class="notif-message">' + escapeHtml(n.message) + '</p>' +
        '<span class="notif-meta">' + escapeHtml(formatDate(n.createdAt)) + (link ? ' &middot; ' + link : '') + '</span>' +
        '</div>' +
        '<span class="notif-state' + (isRead ? ' read' : '') + '">' + (isRead ? 'Read' : 'Unread') + '</span>' +
        '</div>'
      );
    })
    .join('');

  return toolbar + items + (more > 0 ? '<p class="readonly-note">+ ' + more + ' older notification(s) not shown.</p>' : '');
}

// Renders into the given host element and wires the "mark all as read" action.
function renderNotificationPanel(hostId, user, rerender) {
  const host = document.getElementById(hostId);
  if (!host || !user) return;
  host.innerHTML = notificationPanelHtml(user);
  const btn = host.querySelector('[data-mark-read]');
  if (btn) {
    btn.addEventListener('click', function () {
      const changed = markNotificationsRead(user.id);
      if (changed) {
        showAlert(document.getElementById('page-alert'), 'success', changed + ' notification(s) marked as read.');
      }
      if (typeof updateUnreadBadge === 'function') updateUnreadBadge();
      rerender();
    });
  }
}

window.notificationPanelHtml = notificationPanelHtml;
window.renderNotificationPanel = renderNotificationPanel;
